import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const base = process.argv[2] || 'http://localhost:8083'
const browser = await chromium.launch({ channel: 'chrome', args: ['--use-gl=angle', '--use-angle=default'] })
const context = await browser.newContext({ viewport: { width: 390, height: 900 } })
await context.addInitScript(() => localStorage.setItem('age-gate-21', '1'))
const page = await context.newPage()
const errors = []
page.on('pageerror', (error) => errors.push(error.message))

await page.goto(`${base}/explore?static=1`, { waitUntil: 'networkidle' })
const cards = page.locator('.product-card')
assert.equal(await cards.count(), 36)
const kinds = await cards.evaluateAll((all) => Object.fromEntries(all.map((card) => [card.querySelector('h3')?.textContent, card.getAttribute('data-structure-kind')])))
assert.equal(kinds['The Wolverine Blend'], 'blend')
assert.equal(kinds['AOD-9604'], 'sequence')
assert.equal(kinds['Semaglutide'], 'deposited')
assert.equal(kinds['Tirzepatide'], 'deposited')
assert.equal(kinds['GLP3'], 'deposited')
assert.equal(kinds['PT-141 (Bremelanotide)'], 'sequence')
assert.equal(kinds['Cerebrolysin'], 'mixture')
const blend = cards.filter({ has: page.getByRole('heading', { name: 'The Wolverine Blend', exact: true }) })
assert.equal(await blend.locator('.composite-member').count(), 2)
assert.match(await blend.locator('.composite-structure').innerText(), /BPC-157.*TB-500/s)
const cerebral = cards.filter({ has: page.getByRole('heading', { name: 'Cerebrolysin', exact: true }) })
assert.equal(await cerebral.locator('svg, canvas').count(), 0, 'a mixture must not receive an invented molecule')
assert.match(await cerebral.locator('.structure-unavailable').innerText(), /peptide mixture/i)
await blend.scrollIntoViewIfNeeded()
await blend.locator('xpath=..').waitFor({ state: 'visible' })
await page.waitForTimeout(900)
await blend.screenshot({ path: 'shots/portal-refresh/wolverine-two-structures.png' })
for (const name of ['AOD-9604', 'Semaglutide', 'Tirzepatide', 'GLP3', 'Cerebrolysin']) {
  const card = cards.filter({ has: page.getByRole('heading', { name, exact: true }) })
  await card.scrollIntoViewIfNeeded()
  await page.waitForTimeout(1100)
  await card.screenshot({ path: `shots/portal-refresh/${name.toLowerCase()}-structure.png` })
}
await page.goto(`${base}/compound/wolverine-blend?static=1`, { waitUntil: 'networkidle' })
assert.equal(await page.locator('#structure .composite-member').count(), 2)
assert.match(await page.locator('.product-hero dl').innerText(), /BPC-157:.*TB-500:/s)
await page.goto(`${base}/compound/cerebrolysin?static=1`, { waitUntil: 'networkidle' })
assert.equal(await page.locator('#structure canvas, #structure svg').count(), 0)
await page.goto(`${base}/explore?quality=low`, { waitUntil: 'networkidle' })
await page.locator('.shop-select select').first().selectOption('repair')
const liveBlend = page.locator('.product-card[data-structure-kind="blend"]')
await liveBlend.scrollIntoViewIfNeeded()
await page.waitForTimeout(1000)
await liveBlend.screenshot({ path: 'shots/portal-refresh/wolverine-two-structures-3d.png' })
assert.deepEqual(errors, [])
await browser.close()
console.log(JSON.stringify({ cards: 36, kinds, errors }, null, 2))
