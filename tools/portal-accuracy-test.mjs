import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const base = process.argv[2] || 'http://localhost:8083'
const browser = await chromium.launch({ channel: 'chrome', args: ['--use-gl=angle', '--use-angle=default'] })
const context = await browser.newContext({ viewport: { width: 390, height: 900 } })
await context.addInitScript(() => localStorage.setItem('age-gate-21', '1'))
const page = await context.newPage()
const errors = []
page.on('pageerror', (error) => errors.push(error.message))

await page.goto(`${base}/signal`, { waitUntil: 'networkidle' })
await page.locator('.signal-controls select').first().selectOption('wolverine-blend')
let nodes = await page.locator('.signal-node:not(.signal-node-core) span').allTextContents()
assert.deepEqual(nodes.sort(), ['BPC-157', 'TB-500 (Thymosin β4)'].sort())
await page.getByRole('button', { name: 'Connections', exact: true }).click()
let links = await page.locator('.network-relationship .network-compound span:first-child').allTextContents()
assert.deepEqual(links.sort(), nodes.sort())
await page.getByRole('button', { name: 'Timeline', exact: true }).click()
assert.match(await page.locator('.signal-timeline').innerText(), /blend has no single-peptide study timeline/i)
await page.getByRole('button', { name: 'Topic map', exact: true }).click()
assert.equal(await page.locator('.island-names button').filter({ hasText: 'Tirzepatide' }).count(), 1)
assert.equal(await page.locator('.island-names button').filter({ hasText: 'Tirzepatide' }).locator('span').innerText(), '↗')
await page.locator('.signal-controls select').first().selectOption('tirzepatide')
await page.getByRole('button', { name: 'Constellation', exact: true }).click()
nodes = await page.locator('.signal-node:not(.signal-node-core) span').allTextContents()
assert.deepEqual(nodes.sort(), ['Semaglutide', 'GLP3'].sort())

await page.goto(`${base}/explore`, { waitUntil: 'networkidle' })
await page.locator('.shop-select select').first().selectOption('cognitive')
const card = page.locator('.product-card').filter({ has: page.getByRole('heading', { name: 'Cerebrolysin', exact: true }) })
await card.scrollIntoViewIfNeeded()
const title = await card.locator('h3').evaluate((el) => ({ right: el.getBoundingClientRect().right, max: el.parentElement.getBoundingClientRect().right, lines: el.getBoundingClientRect().height / parseFloat(getComputedStyle(el).lineHeight) }))
assert.ok(title.right <= title.max + 1, `Card title overflows: ${JSON.stringify(title)}`)
assert.ok(title.lines < 1.2, `Card title wraps: ${JSON.stringify(title)}`)
for (const width of [320, 390, 768]) {
  await page.setViewportSize({ width, height: 900 })
  await page.locator('.shop-select select').first().selectOption('all')
  const overflowing = await page.locator('.product-card h3').evaluateAll((titles) => titles.filter((el) => el.getBoundingClientRect().right > el.parentElement.getBoundingClientRect().right + 1).map((el) => el.textContent))
  assert.deepEqual(overflowing, [], `Card titles overflow at ${width}px`)
}
await page.setViewportSize({ width: 390, height: 900 })
await page.locator('.shop-select select').first().selectOption('repair')
const bpcCard = page.locator('.product-card').filter({ has: page.getByRole('heading', { name: 'BPC-157', exact: true }) }).first()
await bpcCard.scrollIntoViewIfNeeded()
await page.waitForTimeout(900)
await bpcCard.screenshot({ path: 'shots/portal-refresh/bpc-card-texture.png' })

await page.goto(base, { waitUntil: 'networkidle' })
await page.waitForTimeout(1200)
const hero = page.locator('.hero-shell')
assert.equal(await hero.locator('canvas').count(), 1, 'original 3D hero canvas remains')
await hero.screenshot({ path: 'shots/portal-refresh/hero-start.png' })
const before = await page.locator('.hero-shell .h-full.bg-cyan').evaluate((el) => getComputedStyle(el).transform)
await page.evaluate(() => window.scrollTo(0, innerHeight * 0.8))
await page.waitForTimeout(700)
await hero.screenshot({ path: 'shots/portal-refresh/hero-scroll.png' })
const after = await page.locator('.hero-shell .h-full.bg-cyan').evaluate((el) => getComputedStyle(el).transform)
assert.notEqual(after, before, 'pinned hero scroll progress advances')
const desktop = await browser.newContext({ viewport: { width: 1440, height: 900 } })
await desktop.addInitScript(() => localStorage.setItem('age-gate-21', '1'))
const desktopPage = await desktop.newPage()
desktopPage.on('pageerror', (error) => errors.push(error.message))
await desktopPage.goto(base, { waitUntil: 'networkidle' })
await desktopPage.waitForTimeout(900)
assert.equal(await desktopPage.locator('.hero-shell canvas').count(), 1)
const desktopBefore = await desktopPage.locator('.hero-shell .h-full.bg-cyan').evaluate((el) => getComputedStyle(el).transform)
await desktopPage.evaluate(() => window.scrollTo(0, innerHeight * 1.4))
await desktopPage.waitForTimeout(700)
const desktopAfter = await desktopPage.locator('.hero-shell .h-full.bg-cyan').evaluate((el) => getComputedStyle(el).transform)
assert.notEqual(desktopAfter, desktopBefore, 'desktop pinned hero progress advances')
await desktopPage.locator('.hero-shell').screenshot({ path: 'shots/portal-refresh/hero-desktop-scroll.png' })
assert.deepEqual(errors, [])
await browser.close()
console.log(JSON.stringify({ nodes, title, heroProgressBefore: before, heroProgressAfter: after, desktopBefore, desktopAfter, errors }, null, 2))
