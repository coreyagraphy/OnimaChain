await page.screenshot({ path: 'test-results/experiences-cholesterol.png' })
await page.getByRole('button', { name: 'Clear filters' }).click()
const topicSelect = page.getByLabel('Condition / topic', { exact: true })
const topicValues = await topicSelect.locator('option').evaluateAll(options => options.map(o => o.value).filter(Boolean))
for (const topic of topicValues) {
  await topicSelect.selectOption(topic)
  await page.waitForFunction(topic => new URL(location.href).searchParams.get('topic') === topic, topic)
  if (topic === 'tendon') await page.getByRole('heading', { name: 'How tendon injury connects to the research' }).waitFor()
  else assert.ok(await page.locator('.ex-card').count() > 0, `Topic ${topic} must return reviewed accounts`)
}
