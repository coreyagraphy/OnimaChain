import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'

const base = process.env.EXPERIENCES_TEST_URL || 'http://localhost:8081'
await mkdir('test-results', { recursive: true })
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const response = await page.goto(`${base}/experiences`, { waitUntil: 'networkidle' })
assert.equal(response.status(), 200)
await page.getByRole('heading', { name: 'HUMAN STORIES. THE FULL PICTURE.' }).waitFor()
assert.equal(await page.locator('.ex-card').count(), 36)
await page.screenshot({ path: 'test-results/experiences-desktop.png', fullPage: false })
await page.getByLabel('Search a condition, symptom or compound').fill('eczema')
await page.waitForFunction(() => document.querySelectorAll('.ex-card').length === 1)
assert.ok((await page.locator('.ex-card').innerText()).includes('GHK-Cu'))
await page.reload({ waitUntil: 'networkidle' })
assert.equal(await page.getByLabel('Search a condition, symptom or compound').inputValue(), 'eczema')
assert.equal(await page.locator('.ex-card').count(), 1)
await page.getByRole('button', { name: 'Clear filters' }).click()
await page.getByLabel('Reported outcome', { exact: true }).selectOption('adverse')
await page.waitForFunction(() => [...document.querySelectorAll('.ex-card')].every(e => e.dataset.outcome === 'adverse'))
await page.getByLabel('Compound', { exact: true }).selectOption('bpc-157')
await page.waitForFunction(() => document.querySelectorAll('.ex-card').length === 1)
assert.ok((await page.locator('.ex-card').innerText()).includes('Severe anxiety'))
await page.getByRole('button', { name: 'Clear filters' }).click()
await page.getByRole('button', { name: '5-Amino-1MQ Non-peptide', exact: true }).click()
await page.waitForFunction(() => document.querySelectorAll('.ex-card').length === 2)
assert.equal(await page.locator('.ex-card[data-outcome="adverse"]').count(), 1)
await page.getByRole('button', { name: '21 peptides', exact: false }).click()
await page.getByLabel('Search a condition, symptom or compound').fill('fatty liver')
await page.getByRole('heading', { name: 'No reviewed account matches these filters.' }).waitFor()
await page.getByRole('button', { name: 'Clear filters' }).click()
await page.getByLabel('Search a condition, symptom or compound').fill('sleep and anxiety')
await page.waitForFunction(() => document.querySelectorAll('.ex-card').length > 0 && document.querySelectorAll('.ex-card').length < 5)
await page.getByRole('button', { name: 'Clear filters' }).click()
await page.locator('.ex-results').scrollIntoViewIfNeeded()
await page.screenshot({ path: 'test-results/experiences-cards.png' })
await page.setViewportSize({ width: 390, height: 844 })
await page.goto(`${base}/experiences`, { waitUntil: 'networkidle' })
assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile overflow')
await page.screenshot({ path: 'test-results/experiences-mobile.png', fullPage: false })
await page.getByRole('button', { name: 'Open menu', exact: true }).click()
await page.locator('#mobile-nav').getByRole('link', { name: 'Experiences', exact: true }).click()
assert.equal(await page.locator('#mobile-nav').count(), 0)
await page.getByLabel('Search a condition, symptom or compound').focus()
await page.keyboard.type('sleep')
await page.waitForFunction(() => document.querySelectorAll('.ex-card').length > 0 && document.querySelectorAll('.ex-card').length < 36)
await page.locator('.ex-card').first().locator('summary').focus()
await page.keyboard.press('Enter')
assert.equal(await page.locator('.ex-card').first().locator('details').getAttribute('open'), '')
assert.ok(await page.locator('.ex-card').first().getByText('Public source text reviewed', { exact: false }).isVisible())
assert.deepEqual(errors, [], `Browser errors: ${errors.join('; ')}`)
await browser.close()
console.log('PASS: desktop/mobile, source cards, combined filters, URL persistence, empty state, separate non-peptide collection, keyboard details and navigation.')
