assert.equal(await page.getByRole('link', { name: 'Open the tracked tendon-repair claim and its sources', exact: false }).getAttribute('href'), '/claim/CLAIM-BPC157-TENDON-REPAIR')
assert.equal(await page.locator('.ex-evidence a[href*="pubmed.ncbi.nlm.nih.gov"]').count(), 2)
await search.fill('my leg is swollen after a torn tendon')
await search.press('Enter')
await checkResultsFocus()
await page.getByRole('heading', { name: 'How tendon injury connects to the research' }).waitFor()
assert.equal(await page.locator('.ex-card').count(), 0)
await search.fill('my leg is swollen after injecting retatrutide')
await search.press('Enter')
await checkResultsFocus()
await page.getByRole('heading', { name: 'New leg and foot swelling after starting injections' }).waitFor()
assert.deepEqual(await page.locator('.ex-compounds').allTextContents(), ['Retatrutide'])
